'use strict';
const assert = require('assert');
const protocol = require('../capture/protocol');
function fails(code, fn) { assert.throws(fn, error => error.code === code); }
const token = 'capture:mail:start:r1234567890123abcd';
assert.deepStrictEqual(protocol.parse(token), { scene: 'mail', command: 'start', rid: 'r1234567890123abcd' });
assert.strictEqual(protocol.parse('capture:mail:start:bad'), null);
assert.strictEqual(protocol.parse('recipe:mail:start:r1234567890123abcd'), null);
assert.strictEqual(protocol.parse('capture:../mail:start:r1234567890123abcd'), null);
assert.strictEqual(protocol.parse('capture:_discard:start:r1234567890123abcd'), null);
assert.strictEqual(protocol.slot(null, token), 'write');
fails(2, () => protocol.slot(token, token));
protocol.heartbeat('1000000000000', 1000000010000);
fails(9, () => protocol.heartbeat('1000000000000', 1000000010001));
fails(9, () => protocol.heartbeat('bad', Date.now()));
assert(protocol.canRetry({ sceneId: 'mail', state: 'recording' }, 'mail'));
assert(protocol.canRetry({ sceneId: 'mail', state: 'failed' }, 'mail'));
assert(!protocol.canRetry({ sceneId: 'mail', state: 'closed' }, 'mail'));
assert(!protocol.canRetry({ sceneId: 'other', state: 'failed' }, 'mail'));
assert(protocol.canPull({ state: 'closed' }));
for (const state of ['recording', 'failed', 'discarded']) assert(!protocol.canPull({ state }));
const state = require('../capture/state');
const initial = state.start('mail', 'ld-5554', 'session', 'now');
const frame = state.append(initial, 'later');
assert.strictEqual(initial.frameCount, 0);
assert.strictEqual(frame.frames[0].file, '001.png');
assert.strictEqual(state.close(frame, 'end').state, 'closed');
const failed = state.fail(frame, 'io', 'end');
assert.strictEqual(failed.lastError, 'io');
assert.strictEqual(state.discard(failed, 'end').discardReason, 'failed-retry');
assert.strictEqual(state.discard(frame, 'end').discardReason, 'user-retry');
assert.throws(() => state.append(failed, 'later'));
assert.throws(() => state.discard(state.close(frame, 'end'), 'end'));
console.log('capture protocol and state: OK');
